-- EJECUTAR UNA SOLA VEZ EN CENTRAL, SUC1, SUC2 Y SUC3 (esquemas nuevos).
-- ATENCION: no ejecutar sobre tablas existentes sin migracion o copia de seguridad.
CREATE TABLE catalogo_nodos (
 id_nodo VARCHAR2(10) PRIMARY KEY,
 nombre_sucursal VARCHAR2(50) NOT NULL,
 tipo_conexion VARCHAR2(20) CHECK(tipo_conexion IN ('CONECTADO','DIFERIDO')),
 ultima_sincronizacion TIMESTAMP
);
CREATE TABLE productos (
 id_producto NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 codigo_barra VARCHAR2(50) NOT NULL UNIQUE,
 nombre_medicamento VARCHAR2(100) NOT NULL,
 precio_unitario NUMBER(10,2) NOT NULL CHECK(precio_unitario >= 0),
 stock_actual NUMBER NOT NULL CHECK(stock_actual >= 0),
 fecha_actualizacion TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);
CREATE TABLE clientes (
 id_cliente VARCHAR2(30) PRIMARY KEY,
 cedula VARCHAR2(20) NOT NULL UNIQUE,
 nombre VARCHAR2(100) NOT NULL,
 telefono VARCHAR2(20),
 nodo_origen VARCHAR2(10) NOT NULL,
 sincronizado NUMBER(1) DEFAULT 0 NOT NULL CHECK(sincronizado IN (0,1))
);
CREATE TABLE facturas (
 id_factura NUMBER PRIMARY KEY,
 id_cliente VARCHAR2(30) NOT NULL REFERENCES clientes(id_cliente),
 fecha_emision TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
 total NUMBER(10,2) NOT NULL CHECK(total >= 0),
 nodo_emisor VARCHAR2(10) NOT NULL,
 sincronizado NUMBER(1) DEFAULT 0 NOT NULL CHECK(sincronizado IN (0,1))
);
-- El id_detalle se genera independientemente en cada sucursal.
-- En CENTRAL se conserva el par (nodo_origen, id_detalle_origen) para evitar colisiones.
CREATE TABLE detalle_factura (
 id_detalle NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_factura NUMBER NOT NULL REFERENCES facturas(id_factura) ON DELETE CASCADE,
 id_producto NUMBER NOT NULL REFERENCES productos(id_producto),
 cantidad NUMBER NOT NULL CHECK(cantidad > 0),
 subtotal NUMBER(10,2) NOT NULL CHECK(subtotal >= 0),
 nodo_origen VARCHAR2(10),
 id_detalle_origen NUMBER,
 CONSTRAINT uq_detalle_remoto UNIQUE(nodo_origen,id_detalle_origen),
 CONSTRAINT ck_detalle_origen CHECK (
   (nodo_origen IS NULL AND id_detalle_origen IS NULL)
   OR (nodo_origen IS NOT NULL AND id_detalle_origen IS NOT NULL)
 )
);
CREATE TABLE control_bloques_factura (
 id_nodo VARCHAR2(10) PRIMARY KEY,
 rango_min NUMBER NOT NULL,
 rango_max NUMBER NOT NULL,
 ultimo_valor_usado NUMBER NOT NULL,
 bloque_respaldo_min NUMBER NOT NULL,
 bloque_respaldo_max NUMBER NOT NULL,
 estado_bloque VARCHAR2(20) DEFAULT 'ACTIVO'
);
CREATE TABLE config_nodo (
 id_nodo VARCHAR2(10) PRIMARY KEY
);
CREATE TABLE bitacora_sincronizacion (
 id_bitacora NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nodo VARCHAR2(10) NOT NULL,
 proceso VARCHAR2(50) NOT NULL,
 fecha_ejecucion TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
 estado VARCHAR2(10) NOT NULL CHECK(estado IN ('EXITO','ERROR')),
 registros NUMBER DEFAULT 0 NOT NULL,
 mensaje VARCHAR2(1000)
);
COMMIT;
